import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const recordPath = 'docs/design/system/tokens.json'
export const outputPath = 'docs/design/system/build-check/contrast.md'

const surfaces = ['background', 'card', 'popover', 'muted', 'accent', 'secondary']

function channel(value) {
  const c = value / 255
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((index) => parseInt(hex.slice(index, index + 2), 16))
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
}

export function contrast(a, b) {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (light + 0.05) / (dark + 0.05)
}

export function pairs(record) {
  const text = [
    ...surfaces.map((surface) => ['foreground', surface, 'Body text']),
    ...['background', 'card', 'popover', 'muted', 'accent'].map((surface) => [
      'muted-foreground',
      surface,
      'Hints, metadata, keyboard hints, no-turn words',
    ]),
    ['card-foreground', 'card', 'Text on cards'],
    ['popover-foreground', 'popover', 'Text in overlays'],
    ['primary-foreground', 'primary', 'Primary button label'],
    ['primary', 'background', 'Links'],
    ['primary', 'card', 'Links on cards'],
    ['secondary-foreground', 'secondary', 'Neutral avatar initials'],
    ['accent-foreground', 'accent', 'Hover and selected row'],
    ['destructive', 'background', 'Error text'],
    ['destructive', 'card', 'Error summary links'],
    ['destructive-foreground', 'destructive', 'Destructive fill'],
    ['sidebar-foreground', 'sidebar', 'Desk sidebar'],
    ['sidebar-accent-foreground', 'sidebar-accent', 'Active view'],
    ['sidebar-primary-foreground', 'sidebar-primary', 'Sidebar primary'],
    ...record.roles.flatMap((role) => [
      [`${role}-ink`, 'background', 'State word on the page'],
      [`${role}-ink`, 'card', 'State word on a card or desk chip'],
      [
        `${role}-ink`,
        `${role}-soft`,
        'State word on its tint (client chip, turn bar label, holder)',
      ],
      [`${role}-foreground`, role, 'Turn disc initials, urgent solid chip'],
      ['foreground', `${role}-soft`, 'Body text and turn bar count on the tint'],
    ]),
    ['muted-foreground', 'caution-soft', 'Hint on the client-turn tint'],
    ['muted-foreground', 'progress-soft', 'Hint on the representative-turn tint'],
  ]
  const nonText = [
    ...record.roles.flatMap((role) => [
      [role, 'background', 'Glyph, disc, edge on the page'],
      [role, 'card', 'Glyph, disc, edge on a card'],
      [role, `${role}-soft`, 'Glyph and turn-bar rule on the tint'],
    ]),
    ['input', 'background', 'Input and checkbox boundary'],
    ['input', 'card', 'Input boundary, no-turn dashed disc'],
    ['input', 'muted', 'No-turn dashed outline on muted'],
    ['ring', 'background', 'Focus ring'],
    ['ring', 'card', 'Focus ring on a card'],
    ['ring', 'muted', 'Focus ring on muted'],
    ['primary', 'accent', 'Selected row graphite edge'],
    ['destructive', 'card', 'Error summary border'],
  ]
  return [
    ...text.map(([fg, bg, use]) => ({ kind: 'text', minimum: 4.5, fg, bg, use })),
    ...nonText.map(([fg, bg, use]) => ({ kind: 'non-text', minimum: 3, fg, bg, use })),
  ]
}

export function rows(record) {
  return pairs(record).map((pair) => {
    const [light, dark] = ['light', 'dark'].map((theme) => {
      const values = record.theme[theme]
      return contrast(values[pair.fg], values[pair.bg])
    })
    return {
      ...pair,
      light: Math.round(light * 100) / 100,
      dark: Math.round(dark * 100) / 100,
      passes: light >= pair.minimum && dark >= pair.minimum,
    }
  })
}

export function render(record) {
  const all = rows(record)
  const table = (kind) =>
    all
      .filter((row) => row.kind === kind)
      .map(
        (row) =>
          `| \`--${row.fg}\` on \`--${row.bg}\` | ${row.use} | ${row.light.toFixed(2)} | ${row.dark.toFixed(2)} | ${row.passes ? 'Pass' : 'Fail'} |`,
      )
      .join('\n')
  const lowest = (kind) =>
    Math.min(
      ...all.filter((row) => row.kind === kind).flatMap((row) => [row.light, row.dark]),
    ).toFixed(2)
  return `# Computed contrast: Relay in the app

Generated by \`node scripts/design/contrast-record.mjs\` from \`docs/design/system/tokens.json\`, which \`tests/unit/design/tokens.spec.ts\` proves the app declares value for value. \`tests/unit/design/contrast.spec.ts\` fails if this file is stale or any pair drops below WCAG 2.2 AA. Ratios are WCAG relative-luminance contrast shown to two decimals; the pass check uses the unrounded ratio.

${all.length} pairs per theme: ${all.filter((row) => row.kind === 'text').length} text pairs (at least 4.5:1) and ${all.filter((row) => row.kind === 'non-text').length} non-text pairs (at least 3:1). Lowest text ratio ${lowest('text')}:1, lowest non-text ratio ${lowest('non-text')}:1. Every pair passes in both themes.

The four turn aliases point at caution, progress, positive and seal, and the no-turn style uses muted, muted-foreground, border, input and card, so their pairs are the rows below.

## Text pairs

| Pair | Use | Light | Dark | AA |
|---|---|---|---|---|
${table('text')}

## Non-text pairs

| Pair | Use | Light | Dark | AA |
|---|---|---|---|---|
${table('non-text')}
`
}

export function readRecord() {
  return JSON.parse(readFileSync(recordPath, 'utf8'))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(outputPath, render(readRecord()))
  console.log(`Wrote ${outputPath}`)
}
